#!/usr/bin/env bash
# Regenerate MAP.md — one line per note so the agent can grep instead of opening files.
# Called automatically by sync-vault.sh. Safe to run standalone. No hand-editing MAP.md.
set -e

VAULT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$VAULT"

# Pull a one-line description from a note:
#   frontmatter `description:` → first `**What:**` line → first real paragraph.
describe() {
  awk '
    NR==1 && $0=="---" { fm=1; next }
    fm && $0=="---"    { fm=0; next }
    fm && /^description:/ {
      sub(/^description:[ \t]*/,""); gsub(/^["'"'"']|["'"'"']$/,""); print; exit
    }
    fm { next }
    /^\*\*What:\*\*/ { sub(/^\*\*What:\*\*[ \t]*/,""); print; exit }
    /^[#>|[:space:]]/ { next }
    /^[-*] / { next }
    /^!?\[/ { next }
    NF { print; exit }
  ' "$1"
}

emit_dir() {
  local dir="$1"
  [ -d "$dir" ] || return 0
  echo "## $dir"
  find "$dir" -name '*.md' | LC_ALL=C sort | while IFS= read -r f; do
    d=$(describe "$f"); d="${d:0:140}"
    echo "- \`$f\` — ${d:-"(no description)"}"
  done
  echo
}

{
  echo "# MAP — auto-generated by scripts/build-map.sh (do NOT hand-edit)"
  echo "# One line per note: path — description. Grep this file to find things."
  echo
  emit_dir wiki
  emit_dir projects
} > MAP.md

count=$(grep -c '^- ' MAP.md || echo 0)
echo "🗺️  MAP.md regenerated ($count entries)"
